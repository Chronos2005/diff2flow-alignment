#!/bin/bash
#SBATCH --partition=ecsstudents_l4
#SBATCH --account=ecsstudents
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --gres=gpu:2
#SBATCH --cpus-per-task=12
#SBATCH --time=24:00:00
#SBATCH --output=../logs/exp7_train_%j.out
#SBATCH --error=../logs/exp7_train_%j.err

module load conda
source activate /home/ram1g23/.conda/envs/diffusion_flow_study

export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK

echo "===== ENVIRONMENT CHECK ====="
echo "Job ID: $SLURM_JOB_ID"
echo "Node: $(hostname)"
python - <<EOF
import torch
print("Torch:", torch.__version__, "| CUDA:", torch.cuda.is_available(), "| GPUs:", torch.cuda.device_count())
EOF
echo "===== END CHECK ====="

# ---------------------------------------------------------------------------
# Exp 7: Reflow (Trajectory Straightening)
#
# Trains a pure FM student on straight-line (x0, x1) pairs generated by the
# best fully-aligned Diff2Flow teacher (T+I+V from Exp 1).
#
# The student can then be sampled at NFE = 1-4 with much better FID.
# Evaluate with metrics_fm.py (pure FM, no aligner).
# ---------------------------------------------------------------------------

TEACHER_CKPT=/scratch/ram1g23/fm_cifar10_long2/final_model_ema
OUTPUT_DIR=/scratch/ram1g23/exp7_reflow

echo "Teacher: ${TEACHER_CKPT}"
echo "Output:  ${OUTPUT_DIR}"

accelerate launch --num_processes=2 --mixed_precision="bf16" ../../training_scripts/train_reflow.py \
  --teacher_checkpoint ${TEACHER_CKPT} \
  --teacher_type fm \
  --student_init pretrained \
  --image_size 32 \
  --num_epochs 20 \
  --steps_per_epoch 1000 \
  --train_batch_size 128 \
  --teacher_num_steps 50 \
  --num_inference_steps 10 \
  --save_images_every 5 \
  --save_model_every 5 \
  --seed 42 \
  --output_dir ${OUTPUT_DIR}
